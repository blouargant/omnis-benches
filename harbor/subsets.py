#!/usr/bin/env python3
"""Print the task names of a Harness Leaderboard subset, one per line.

Subsets are copied from the leaderboard's hlb/data/benchmarks.json (Space
joelniklaus/harness-leaderboard, generated by its scripts/build_subsets.py,
seed 20261014) into subsets.json so a run is reproducible offline. ``full``
is every task of the subset file; an argument containing commas is taken as
an explicit task list.
"""
import json
import sys
from pathlib import Path

ALIAS = {"tb": "terminal-bench-2.1", "deepswe": "deep-swe"}


def names(bench: str, subset: str) -> list[str]:
    if "," in subset or subset not in ("smoke", "pilot", "full"):
        return [s for s in subset.split(",") if s]
    data = json.loads((Path(__file__).with_name("subsets.json")).read_text())
    return data[ALIAS.get(bench, bench)][subset]


if __name__ == "__main__":
    print("\n".join(names(sys.argv[1], sys.argv[2])))
